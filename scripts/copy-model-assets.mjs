#!/usr/bin/env node
/**
 * Puts the self-hosted engines of the live camera recognition (Phase 7a-2) into public/
 * (git-ignored), so nothing is fetched from Hugging Face or a CDN at run time:
 *
 *   public/models/clip-vit-base-patch32/   CLIP ViT-B/32 (quantized ONNX, ~85 MB)
 *   public/ort/                            ONNX Runtime Web .wasm / .mjs engine files
 *   public/opencv/opencv.js                OpenCV.js (ORB verification, loaded on demand)
 *
 * Runs before `dev` and `build`. Idempotent. The model comes from, in order:
 *   1. a directory in MODEL_SOURCE_DIR (already containing config.json, ...),
 *   2. the local Transformers.js cache in node_modules,
 *   3. a one-time download from huggingface.co (build time only, never at run time).
 * Set SKIP_MODEL_ASSETS=1 to skip it (e.g. when the model is hosted elsewhere).
 */
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  renameSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { Readable } from "node:stream";
import { pipeline } from "node:stream/promises";
import { createWriteStream } from "node:fs";

if (process.env.SKIP_MODEL_ASSETS === "1") {
  console.log("copy-model-assets: skipped (SKIP_MODEL_ASSETS=1)");
  process.exit(0);
}

const root = process.cwd();
const nm = (...p) => join(root, "node_modules", ...p);
const out = (...p) => join(root, "public", ...p);

const MODEL = "clip-vit-base-patch32";
const HF = `https://huggingface.co/Xenova/${MODEL}/resolve/main`;
const MODEL_FILES = [
  { file: "config.json", minBytes: 100 },
  { file: "preprocessor_config.json", minBytes: 100 },
  { file: "onnx/vision_model_quantized.onnx", minBytes: 60 * 1024 * 1024 },
];

/** ONNX Runtime Web engine files the browser build loads (single-thread CPU wasm). */
const ORT_FILES = (process.env.ORT_FILES ?? "ort-wasm-simd-threaded.mjs,ort-wasm-simd-threaded.wasm").split(",");

function fail(message) {
  console.error(`copy-model-assets: ${message}`);
  process.exit(1);
}

function ensureCopy(from, to, minBytes = 1) {
  if (!existsSync(from)) fail(`missing source ${from} (run npm install)`);
  if (existsSync(to) && statSync(to).size === statSync(from).size) return false;
  mkdirSync(dirname(to), { recursive: true });
  copyFileSync(from, to);
  if (statSync(to).size < minBytes) fail(`${to} is smaller than expected`);
  return true;
}

async function download(url, to, minBytes) {
  const res = await fetch(url, { redirect: "follow" });
  if (!res.ok || !res.body) fail(`download failed (${res.status}) for ${url}`);
  mkdirSync(dirname(to), { recursive: true });
  const tmp = `${to}.part`;
  await pipeline(Readable.fromWeb(res.body), createWriteStream(tmp));
  if (statSync(tmp).size < minBytes) fail(`downloaded ${url} is smaller than expected`);
  renameSync(tmp, to);
}

let changed = 0;

// --- the model ----------------------------------------------------------------------
const sources = [
  process.env.MODEL_SOURCE_DIR,
  nm("@huggingface", "transformers", ".cache", "Xenova", MODEL),
].filter(Boolean);

for (const { file, minBytes } of MODEL_FILES) {
  const to = out("models", MODEL, file);
  if (existsSync(to) && statSync(to).size >= minBytes) continue;
  const local = sources.map((dir) => join(dir, file)).find((p) => existsSync(p));
  if (local) {
    ensureCopy(local, to, minBytes);
    console.log(`copy-model-assets: copied ${file} from ${local}`);
  } else {
    console.log(`copy-model-assets: downloading ${file} from huggingface.co (one time)...`);
    await download(`${HF}/${file}`, to, minBytes);
  }
  changed++;
}

// --- ONNX Runtime Web engine --------------------------------------------------------
for (const file of ORT_FILES)
  if (ensureCopy(nm("onnxruntime-web", "dist", file), out("ort", file))) changed++;

// --- OpenCV.js ----------------------------------------------------------------------
if (ensureCopy(nm("@techstark", "opencv-js", "dist", "opencv.js"), out("opencv", "opencv.js")))
  changed++;

writeFileSync(out("models", ".gitkeep-note"), "Generated by scripts/copy-model-assets.mjs; git-ignored.\n");
console.log(`copy-model-assets: up to date (${changed} changed)`);
